/* eslint-disable @typescript-eslint/no-require-imports */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require(process.env.PGLITE_MODULE || path.join(process.env.TEMP, 'urbanite-identity-sql/node_modules/@electric-sql/pglite'));
const migration = fs.readFileSync(path.join(__dirname, '../supabase/migration-business-identity.sql'), 'utf8');
(async () => {
  const db = new PGlite();
  await db.exec(`create role anon; create role authenticated;
    create table shops (id uuid primary key, slug text unique not null, name text not null, owner_user_id uuid);
    create table profile_cards (id uuid primary key, slug text unique not null, display_name text not null, owner_user_id uuid unique, updated_at timestamptz);
    create table bk_businesses (id uuid primary key, card_id uuid, owner_user_id uuid unique, name text not null, updated_at timestamptz);`);
  const a = '00000000-0000-0000-0000-000000000001', b = '00000000-0000-0000-0000-000000000002', s = '00000000-0000-0000-0000-000000000003';
  await db.query('insert into profile_cards values ($1,$2,$3,$1,now())', [a, 'original', 'Original']);
  await db.query('insert into shops values ($1,$2,$3,$4)', [s, 'existing-shop', 'Existing', b]);
  await db.exec(migration);
  await db.exec(migration);
  const one = async sql => (await db.query(sql)).rows[0];
  assert.equal((await one('select display_name from profile_cards')).display_name, 'Original');
  await db.query('update profile_cards set business_identity=true, slug=$1, display_name=$2 where id=$3', ['my-store', 'My Store', a]);
  await db.query('insert into bk_businesses values ($1,$1,$1,$2,now())', [a, '']);
  assert.equal((await one('select name from bk_businesses')).name, 'My Store');
  await assert.rejects(db.query('insert into shops values ($1,$2,$3,$4)', [a, 'my-store', 'My Store', b]), /already used/);
  await assert.rejects(db.query('insert into shops values ($1,$2,$3,$4)', [a, 'wrong-store', 'My Store', a]), /confirmed/);
  await db.query('insert into shops values ($1,$2,$3,$1)', [a, 'my-store', 'My Store']);
  assert.equal((await one(`select shop_id from profile_cards where id='${a}'`)).shop_id, a);
  await db.query('update profile_cards set display_name=$1,slug=$2 where id=$3', ['Renamed', 'new-store', a]);
  assert.equal((await one(`select name,slug from shops where id='${a}'`)).name, 'Renamed');
  assert.equal((await one('select name from bk_businesses')).name, 'Renamed');
  await db.query('update bk_businesses set name=$1 where id=$2', ['Booking name', a]);
  assert.equal((await one('select display_name from profile_cards')).display_name, 'Booking name');
  assert.equal((await one(`select name from shops where id='${a}'`)).name, 'Booking name');
  await db.query('update shops set name=$1 where id=$2', ['Shop name', a]);
  assert.equal((await one('select display_name from profile_cards')).display_name, 'Shop name');
  await assert.rejects(db.query('update profile_cards set shop_id=$1 where id=$2', [s, a]), /owner mismatch/);
  await assert.rejects(db.query('update shops set owner_user_id=$1 where id=$2', [b, a]), /owner mismatch/);
  await assert.rejects(db.query('update bk_businesses set name=$1 where id=$2', ['', a]), /Invalid shared/);
  assert.equal((await one('select name from bk_businesses')).name, 'Shop name');
  await assert.rejects(db.query('update profile_cards set slug=$1 where id=$2', ['bad.slug', a]), /Invalid shared/);
  await db.query('insert into profile_cards (id,slug,display_name,owner_user_id) values ($1,$2,$3,$1)', [b, 'other-store', 'Other']);
  await db.query('update profile_cards set business_identity=true where id=$1', [b]);
  await assert.rejects(db.query('update profile_cards set slug=$1 where id=$2', ['other-store', a]), /duplicate/);
  assert.equal((await one(`select slug from shops where id='${a}'`)).slug, 'new-store');
  await db.query('delete from shops where id=$1', [a]);
  assert.equal((await one(`select shop_id from profile_cards where id='${a}'`)).shop_id, null);
  assert.equal((await one(`select name from shops where id='${s}'`)).name, 'Existing');
  await db.close();
  console.log('Shared identity SQL passed: idempotent migration, legacy preservation, reservations, ownership, automatic linking, three-way sync, rollback, deletion. Local isolated PostgreSQL only.');
})().catch(error => { console.error(error); process.exit(1); });
